#Arthmetic Operators --->These operators are used to perform arthmetic operations 

#like addition,subtraction,multiplication,division,floor division,moudule(remainder),Exponential operator

a=10
b=20
res=a+b  #10+20 -->30
print(res)

res=a-b #10-20 --->-10
print(res)

res=a*b  #10*20 ----->200
print(res)

res=a/b #10/20 ---->0.0
print(res)

res=a//b  #10//20 -->0
print(res)

res=a%b  #10%20 --->10
print(res)

res=a**b   #10**20 (10 pow20)
print(res)
